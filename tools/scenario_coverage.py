"""Generate docs/scenarios.md: which Agent.md scenario IDs have tests (and regression cases).

Scenario IDs are collected from ``@pytest.mark.scenario("X.n")`` markers, parametrised
scenario columns in tests, and ``scenario:`` fields in tests/regression/cases.yaml.
Usage: uv run python tools/scenario_coverage.py
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PHASE1 = (
    [f"A.{i}" for i in range(1, 21)]
    + [f"B.{i}" for i in range(1, 13)]
    + [f"C.{i}" for i in range(1, 15)]
    + [f"D.{i}" for i in range(1, 9)]
    + [f"E.{i}" for i in range(1, 7)]
    + [f"F.{i}" for i in range(1, 7)]
    + [f"H.{i}" for i in range(1, 9)]
    + [f"I.{i}" for i in range(1, 7)]
)
ALSO_COVERED = [
    "C.15",
    "C.16",
    "C.17",
    "C.18",
    "C.19",
    "C.20",
    "C.21",
    "C.22",
    "C.24",
    "D.10",
    "D.11",
    "D.12",
    "L.1",
    "L.6",
    "L.7",
    "L.8",
    "O.1",
    "O.4",
]
SCENARIO_RE = re.compile(r"""(?:scenario\(|\(\s*)["']([A-O]\.\d+)["']""")
BENCHMARK = {"C.1", "C.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.19", "C.20", "C.21", "C.22"}


def collect() -> tuple[dict[str, set[str]], set[str]]:
    found: dict[str, set[str]] = defaultdict(set)
    for path in (ROOT / "tests").rglob("test_*.py"):
        for m in SCENARIO_RE.finditer(path.read_text(encoding="utf-8")):
            found[m.group(1)].add(path.relative_to(ROOT).as_posix())
    cases = yaml.safe_load((ROOT / "tests/regression/cases.yaml").read_text(encoding="utf-8"))
    regression = {c["scenario"] for c in cases["cases"]}
    return found, regression


def main() -> int:
    found, regression = collect()
    lines = [
        "# Scenario coverage",
        "",
        "Generated by `tools/scenario_coverage.py` from test markers. Scenario IDs refer to",
        "Agent.md section 5. **R** = frozen regression case exists; **B** = also exercised by the",
        "generated recall benchmark (every list name x obfuscation x field).",
        "",
        "| Scenario | Phase | Tests | R | B |",
        "|---|---|---|---|---|",
    ]
    missing = []
    for sid in [*PHASE1, *[s for s in ALSO_COVERED if s not in PHASE1]]:
        files = sorted(found.get(sid, set()))
        phase = "1" if sid in PHASE1 else "1 (early)"
        if not files:
            missing.append(sid)
        lines.append(
            f"| {sid} | {phase} | {'<br>'.join(files) or '**MISSING**'} | "
            f"{'R' if sid in regression else ''} | {'B' if sid in BENCHMARK else ''} |"
        )
    lines += ["", f"Phase 1 scenarios without a test: {', '.join(missing) or 'none'}", ""]
    out = ROOT / "docs" / "scenarios.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}; missing: {missing or 'none'}")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
